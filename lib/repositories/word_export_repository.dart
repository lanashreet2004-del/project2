/// Handles Word (.docx) export (backend download), sharing, and file access.
/// Offline [generateDocxBytes] remains for tests/offline utilities only.
class WordExportRepository extends BaseRepository {
  WordExportRepository({
    required super.apiService,
    required super.storageService,
  });

  /// Downloads a backend-generated DOCX for the OCR record and saves it locally.
  Future<File?> exportDocumentToWord(HistoryModel document) async {
    final backendId = HistoryRepository.parseBackendId(document.id);
    if (backendId == null) {
      throw ApiException(
        'This document cannot be exported from the server.',
      );
    }

    try {
      final response = await apiService.get<List<int>>(
        ApiConstants.ocrExportDocx(backendId),
        options: Options(responseType: ResponseType.bytes),
      );

      final data = response.data;
      if (data == null || data.isEmpty) {
        throw ApiException('Empty DOCX response from server.');
      }

      final bytes = Uint8List.fromList(data);
      if (!_looksLikeDocx(bytes)) {
        throw ApiException('Server did not return a valid Word file.');
      }

      final preferredName = _fileNameFromHeaders(
        response.headers,
        backendId,
      );
      return _writeDocxBytes(bytes, preferredName);
    } on DioException catch (e) {
      throw _exceptionFromExportDio(e);
    }
  }

  /// Human-readable title derived from OCR text.
  String documentTitleOf(HistoryModel document) {
    return _documentTitle(document.extractedText);
  }

  /// Builds a DOCX report in memory using bundled Arabic fonts (offline).
  /// Used by tests / offline utilities — not by Document Details Export Word.
  Future<List<int>?> generateDocxBytes(HistoryModel document) async {
    try {
      final regularFontBytes =
          (await rootBundle.load(ExportConstants.arabicRegularFontAsset))
              .buffer
              .asUint8List();
      final boldFontBytes =
          (await rootBundle.load(ExportConstants.arabicBoldFontAsset))
              .buffer
              .asUint8List();

      final savedDate = _formatDateTime(document.createdAt);
      final documentTitle = _documentTitle(document.extractedText);

      final builder = docx()
        ..addFont(ExportConstants.wordFontRegularFamily, regularFontBytes)
        ..addFont(ExportConstants.wordFontBoldFamily, boldFontBytes)
        ..add(_spacerParagraph())
        ..add(
          _paragraph(
            ExportConstants.appExportTitle,
            bold: true,
            fontSizeHalfPoints: 52,
            align: 'center',
          ),
        )
        ..add(
          _paragraph(
            'OCR Document Report',
            fontSizeHalfPoints: 24,
            align: 'center',
          ),
        )
        ..add(_spacerParagraph())
        ..add(
          _paragraph(
            'Document Information',
            bold: true,
            fontSizeHalfPoints: 32,
          ),
        )
        ..add(_spacerParagraph())
        ..add(_infoLine('Document Title', documentTitle))
        ..add(_infoLine('Document ID', document.id))
        ..add(_infoLine('Created Date', savedDate))
        ..add(_spacerParagraph())
        ..add(
          _paragraph(
            'Extracted Text',
            bold: true,
            fontSizeHalfPoints: 32,
          ),
        )
        ..add(_spacerParagraph());

      for (final paragraph in _extractedTextParagraphs(document.extractedText)) {
        builder.add(paragraph);
      }

      builder.add(
        _paragraph(
          'Generated by ${ExportConstants.appExportTitle} - '
          '${_formatDateTime(DateTime.now())}',
          fontSizeHalfPoints: 18,
          align: 'right',
        ),
      );

      final doc = builder.build();
      return DocxExporter().exportToBytes(doc);
    } catch (_) {
      return null;
    }
  }

  Future<void> shareExportedFile(File file) async {
    if (!await file.exists()) return;

    await Share.shareXFiles(
      [
        XFile(
          file.path,
          mimeType:
              'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        ),
      ],
      subject: '${ExportConstants.appExportTitle} Report',
      text: 'Exported OCR document Word file',
    );
  }

  Future<void> openExportedFile(File file) async {
    if (!await file.exists()) return;

    await OpenFilex.open(
      file.path,
      type:
          'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    );
  }

