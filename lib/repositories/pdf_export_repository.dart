  /// Downloads a backend-generated PDF for the OCR record and saves it locally.
  ///
  /// [status] is unused (kept for call-site compatibility). PDF layout comes
  /// entirely from the Django export API.
  Future<File?> exportDocumentToPdf(
    HistoryModel document, {
    String status = '',
  }) async {
    final backendId = HistoryRepository.parseBackendId(document.id);
    if (backendId == null) {
      throw ApiException(
        'This document cannot be exported from the server.',
      );
    }

    try {
      final response = await apiService.get<List<int>>(
        ApiConstants.ocrExportPdf(backendId),
        options: Options(responseType: ResponseType.bytes),
      );

      final data = response.data;
      if (data == null || data.isEmpty) {
        throw ApiException('Empty PDF response from server.');
      }

      final bytes = Uint8List.fromList(data);
      if (!_looksLikePdf(bytes)) {
        throw ApiException('Server did not return a valid PDF file.');
      }

      final preferredName = _fileNameFromHeaders(
        response.headers,
        backendId,
      );
      return _writePdfBytes(bytes, preferredName);
    } on DioException catch (e) {
      throw _exceptionFromExportDio(e);
    }
  }

  /// Human-readable title derived from OCR text (same as PDF report title).
  String documentTitleOf(HistoryModel document) {
    return _documentTitle(document.extractedText);
  }

  /// Builds a PDF report in memory using bundled Arabic fonts (offline).
  /// Used by tests / offline utilities — not by Document Details Export PDF.
  Future<Uint8List?> generatePdfBytes(
    HistoryModel document, {
    required String status,
  }) async {
    try {
      final regularFont = await _getRegularFont();
      final boldFont = await _getBoldFont();
      final latinRegularFont = _getLatinRegularFont();
      final latinBoldFont = _getLatinBoldFont();
      final imageBytes = await _loadImageBytes(document.imagePath);
      final savedDate = _formatDateTime(document.createdAt);
      final stats = _computeTextStats(document.extractedText);
      final documentTitle = _documentTitle(document.extractedText);

      final pdf = pw.Document();

      pdf.addPage(
        pw.MultiPage(
          pageTheme: pw.PageTheme(
            margin: const pw.EdgeInsets.symmetric(horizontal: 40, vertical: 36),
            theme: pw.ThemeData.withFont(
              base: regularFont,
              bold: boldFont,
              fontFallback: [latinRegularFont, latinBoldFont],
            ),
          ),
          footer: (context) => pw.Container(
            alignment: pw.Alignment.centerRight,
            child: pw.Text(
              'Generated by ${ExportConstants.appExportTitle} - '
              '${_formatDateTime(DateTime.now())}',
              style: _regularTextStyle(
                regularFont,
                latinRegularFont,
                fontSize: 9,
                color: PdfColors.grey600,
              ),
            ),
          ),
          build: (context) => [
            _buildHeader(boldFont, regularFont, latinRegularFont, latinBoldFont),
            pw.SizedBox(height: 28),
            _buildSectionTitle(
              'Document Information',
              boldFont,
              latinBoldFont,
            ),
            pw.SizedBox(height: 12),
            _buildInfoCard(
              regularFont: regularFont,
              boldFont: boldFont,
              latinRegularFont: latinRegularFont,
              latinBoldFont: latinBoldFont,
              rows: [
                _InfoRow('Document Title', documentTitle),
                _InfoRow('Document ID', document.id),
                _InfoRow('Created Date', savedDate),
                _InfoRow('Status', status),
              ],
            ),
            pw.SizedBox(height: 24),
            _buildSectionTitle('Statistics', boldFont, latinBoldFont),
            pw.SizedBox(height: 12),
            _buildInfoCard(
              regularFont: regularFont,
              boldFont: boldFont,
              latinRegularFont: latinRegularFont,
              latinBoldFont: latinBoldFont,
              rows: [
                _InfoRow('Characters', stats.characters.toString()),
                _InfoRow('Words', stats.words.toString()),
                _InfoRow('Lines', stats.lines.toString()),
              ],
            ),
            pw.SizedBox(height: 24),
            if (imageBytes != null) ...[
              _buildSectionTitle('Original Image', boldFont, latinBoldFont),
              pw.SizedBox(height: 12),
              pw.Center(
                child: pw.Container(
                  padding: const pw.EdgeInsets.all(8),
                  decoration: pw.BoxDecoration(
                    border: pw.Border.all(color: PdfColors.grey300),
                    borderRadius: pw.BorderRadius.circular(12),
                  ),
                  child: pw.ClipRRect(
                    horizontalRadius: 8,
                    verticalRadius: 8,
                    child: pw.Image(
                      pw.MemoryImage(imageBytes),
                      fit: pw.BoxFit.contain,
                      height: 280,
                    ),
                  ),
                ),
              ),
              pw.SizedBox(height: 24),
            ],
            _buildSectionTitle('Extracted Text', boldFont, latinBoldFont),
            pw.SizedBox(height: 12),
            _buildExtractedTextSection(
              document.extractedText,
              regularFont,
              latinRegularFont,
            ),
          ],
        ),
      );

      return pdf.save();
    } catch (_) {
      return null;
    }
  }

