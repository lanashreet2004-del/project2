    const arabicText =
        'مرحباً بكم في تطبيق مكتوب.\n\n'
        'هذا نص تجريبي مستخرج من الصورة باستخدام تقنية التعرف الضوئي على الحروف.\n'
        'يمكنك تعديل هذا النص بالضغط على زر "تعديل النص".';

    final document = HistoryModel(
      id: 'arabic_pdf_test',
      imagePath: '',
      extractedText: arabicText,
      confidence: 0.95,
      createdAt: DateTime.now(),
    );

    final bytes = await _generateArabicTestPdfBytes(
      document: document,
      status: 'تمت المعالجة، تم التحرير',
    );
    if (bytes == null) return null;

    try {
      final directory = await _ensureExportsDirectory();
      final file = File(
        '${directory.path}/${ExportConstants.arabicTestReportFileName}',
      );
      await file.writeAsBytes(bytes);
      return file;
    } catch (_) {
      return null;
    }
  }

