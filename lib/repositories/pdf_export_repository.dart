  pw.Widget _buildExtractedTextSection(
    String text,
    pw.Font regularFont,
    pw.Font latinRegularFont,
  ) {
    final displayText = text.trim().isEmpty ? 'No text extracted.' : text;
    final isRtl = _containsArabic(displayText);

    final content = pw.Text(
      displayText,
      style: _regularTextStyle(
        regularFont,
        latinRegularFont,
        fontSize: 14,
        lineSpacing: 8,
      ),
      textAlign: isRtl ? pw.TextAlign.right : pw.TextAlign.left,
    );

    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(16),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey300),
        borderRadius: pw.BorderRadius.circular(12),
      ),
      child: isRtl
          ? pw.Directionality(
              textDirection: pw.TextDirection.rtl,
              child: content,
            )
          : content,
    );
  }

