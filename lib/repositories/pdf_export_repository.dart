  pw.Widget _buildInfoCard({
    required pw.Font regularFont,
    required pw.Font boldFont,
    required pw.Font latinRegularFont,
    required pw.Font latinBoldFont,
    required List<_InfoRow> rows,
  }) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(16),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey300),
        borderRadius: pw.BorderRadius.circular(12),
        color: PdfColors.grey50,
      ),
      child: pw.Column(
        children: [
          for (var i = 0; i < rows.length; i++) ...[
            pw.Row(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.SizedBox(
                  width: 130,
                  child: _buildLabelText(
                    rows[i].label,
                    boldFont,
                    latinBoldFont,
                  ),
                ),
                pw.Expanded(
                  child: _buildValueText(
                    rows[i].value,
                    regularFont,
                    latinRegularFont,
                  ),
                ),
              ],
            ),
            if (i < rows.length - 1) pw.SizedBox(height: 10),
          ],
        ],
      ),
    );
  }

  pw.Widget _buildLabelText(
    String text,
    pw.Font font,
    pw.Font latinFont,
  ) {
    final isRtl = _containsArabic(text);
    final child = pw.Text(
      text,
      style: _boldTextStyle(
        font,
        latinFont,
        fontSize: 11,
        color: PdfColors.grey700,
      ),
      textAlign: isRtl ? pw.TextAlign.right : pw.TextAlign.left,
    );

    if (!isRtl) return child;

    return pw.Directionality(
      textDirection: pw.TextDirection.rtl,
      child: child,
    );
  }

  pw.Widget _buildValueText(
    String text,
    pw.Font font,
    pw.Font latinFont,
  ) {
    final isRtl = _containsArabic(text);
    final child = pw.Text(
      text,
      style: _regularTextStyle(
        font,
        latinFont,
        fontSize: 11,
        color: PdfColors.grey900,
      ),
      textAlign: isRtl ? pw.TextAlign.right : pw.TextAlign.left,
    );

    if (!isRtl) return child;

    return pw.Directionality(
      textDirection: pw.TextDirection.rtl,
      child: child,
    );
  }

  pw.Widget _buildExtractedTextSection(
    String text,
    pw.Font regularFont,
    pw.Font latinRegularFont,
  ) {
    final displayText = text.trim().isEmpty ? 'No text extracted.' : text;
    final isRtl = _containsArabic(displayText);

    final content = pw.Text(
      displayText,
      style: _regularTextStyle(
        regularFont,
        latinRegularFont,
        fontSize: 14,
        lineSpacing: 8,
      ),
      textAlign: isRtl ? pw.TextAlign.right : pw.TextAlign.left,
    );

    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(16),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey300),
        borderRadius: pw.BorderRadius.circular(12),
      ),
      child: isRtl
          ? pw.Directionality(
              textDirection: pw.TextDirection.rtl,
              child: content,
            )
          : content,
    );
  }

  pw.TextStyle _regularTextStyle(
    pw.Font font,
    pw.Font latinFont, {
    required double fontSize,
    PdfColor? color,
    double? lineSpacing,
  }) {
    return pw.TextStyle(
      font: font,
      fontFallback: [latinFont],
      fontSize: fontSize,
      color: color,
      lineSpacing: lineSpacing,
    );
  }

  pw.TextStyle _boldTextStyle(
    pw.Font font,
    pw.Font latinFont, {
    required double fontSize,
    PdfColor? color,
  }) {
    return pw.TextStyle(
      font: font,
      fontFallback: [latinFont],
      fontSize: fontSize,
      color: color,
      fontWeight: pw.FontWeight.bold,
    );
  }

  Future<pw.Font> _getRegularFont() async {
    _regularFont ??= pw.Font.ttf(
      (await rootBundle.load(ExportConstants.arabicRegularFontAsset))
          .buffer
          .asByteData(),
    );
    return _regularFont!;
  }

  Future<pw.Font> _getBoldFont() async {
    _boldFont ??= pw.Font.ttf(
      (await rootBundle.load(ExportConstants.arabicBoldFontAsset))
          .buffer
          .asByteData(),
    );
    return _boldFont!;
  }

  pw.Font _getLatinRegularFont() {
    return _latinRegularFont ??= pw.Font.helvetica();
  }

  pw.Font _getLatinBoldFont() {
    return _latinBoldFont ??= pw.Font.helveticaBold();
  }

  Future<Uint8List?> _loadImageBytes(String path) async {
    if (path.isEmpty) return null;

    final file = File(path);
    if (!await file.exists()) return null;

    return file.readAsBytes();
  }

  Future<Directory> _ensureExportsDirectory() async {
    final baseDirectory = await getApplicationDocumentsDirectory();
    final exportsDirectory = Directory(
      '${baseDirectory.path}/${ExportConstants.exportsFolderName}',
    );

    if (!await exportsDirectory.exists()) {
      await exportsDirectory.create(recursive: true);
    }

    return exportsDirectory;
  }

  Future<Directory> _ensurePdfExportsDirectory() async {
    final baseDirectory = await _ensureExportsDirectory();
    final pdfDirectory = Directory(
      '${baseDirectory.path}/${ExportConstants.pdfExportsSubfolder}',
    );

    if (!await pdfDirectory.exists()) {
      await pdfDirectory.create(recursive: true);
    }

    return pdfDirectory;
  }

  String _buildUniquePdfFileName(String title) {
    final base = _sanitizeFileName(title);
    final stamp = DateTime.now().millisecondsSinceEpoch;
    return '${base}_$stamp${ExportConstants.pdfFileExtension}';
  }

  String _sanitizeFileName(String input) {
    var name = input.trim();
    if (name.isEmpty) name = 'document';

    name = name.replaceAll(RegExp(r'[<>:"/\\|?*\x00-\x1F]'), '_');
    name = name.replaceAll(RegExp(r'\s+'), ' ').trim();
    if (name.endsWith('.')) {
      name = name.substring(0, name.length - 1).trim();
    }

    const maxLength = 60;
    if (name.length > maxLength) {
      name = name.substring(0, maxLength).trim();
    }

    return name.isEmpty ? 'document' : name;
  }

  String _formatDateTime(DateTime dateTime) {
    final day = dateTime.day.toString().padLeft(2, '0');
    final month = dateTime.month.toString().padLeft(2, '0');
    final year = dateTime.year;
    final hour = dateTime.hour.toString().padLeft(2, '0');
    final minute = dateTime.minute.toString().padLeft(2, '0');
    return '$day/$month/$year - $hour:$minute';
  }

  String _documentTitle(String extractedText) {
    final trimmed = extractedText.trim();
    if (trimmed.isEmpty) return 'Untitled Document';

    final firstLine = trimmed.split('\n').first.trim();
    if (firstLine.isEmpty) return 'Untitled Document';

    const maxLength = 80;
    if (firstLine.length <= maxLength) return firstLine;
    return '${firstLine.substring(0, maxLength)}...';
  }

  _TextStats _computeTextStats(String text) {
    final trimmed = text.trim();
    final characters = text.length;
    final words = trimmed.isEmpty
        ? 0
        : trimmed.split(RegExp(r'\s+')).where((word) => word.isNotEmpty).length;
    final lines = text.isEmpty ? 0 : text.split('\n').length;

    return _TextStats(
      characters: characters,
      words: words,
      lines: lines,
    );
  }

  bool _containsArabic(String text) {
    return RegExp(r'[\u0600-\u06FF]').hasMatch(text);
  }
}

class _InfoRow {
  const _InfoRow(this.label, this.value);

  final String label;
  final String value;
}

class _TextStats {
  const _TextStats({
    required this.characters,
    required this.words,
    required this.lines,
  });

  final int characters;
  final int words;
  final int lines;
}
